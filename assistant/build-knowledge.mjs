// Builds the assistant's knowledge from the published site, so it can only
// repeat what sereinora.com already says. Run after any page change:
//   node assistant/build-knowledge.mjs
// Output: assistant/worker/src/knowledge.js (bundled into the Worker).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
// Public pages the assistant may draw on (the art page /elements/ is excluded: it is not about the service).
const PAGES = ['/', '/check/', '/audit/', '/sample/', '/about/', '/answers/', '/answers/pro-letter/',
  '/answers/spotify-for-business/', '/answers/small-business-exemption/', '/answers/live-music-dj-karaoke/',
  '/answers/ascap-bmi-sesac-gmr/', '/answers/music-license-cost/', '/terms/', '/privacy/'];

const ENT = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'", nbsp: ' ', rsquo: '’', lsquo: '‘', ldquo: '“', rdquo: '”', mdash: '—', ndash: '–', sect: '§', hellip: '…' };
const decode = (s) => s.replace(/&(#\d+|#x[0-9a-f]+|\w+);/gi, (m, e) =>
  e[0] === '#' ? String.fromCodePoint(e[1] === 'x' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10)) : (ENT[e] ?? m));

function pageText(path) {
  let html = readFileSync(join(root, path, 'index.html'), 'utf8');
  const title = decode((html.match(/<title>(.*?)<\/title>/s) || [, ''])[1]).trim();
  html = (html.match(/<main[^>]*>([\s\S]*?)<\/main>/) || [, ''])[1];
  html = html
    .replace(/<(script|style|svg|noscript)[\s\S]*?<\/\1>/gi, '')
    // Keep link targets so the assistant can point to sources and pages.
    .replace(/<a [^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/gi, (m, href, text) => {
      const t = text.replace(/<[^>]+>/g, '').trim();
      const url = href.startsWith('/') ? 'https://sereinora.com' + href : href;
      return url.startsWith('mailto:') || url.startsWith('#') ? t : `${t} (${url})`;
    })
    // Interactive day-map notes live in data attributes; keep them as text.
    .replace(/data-title="([^"]*)" data-text="([^"]*)"/g, '> $1: $2 <')
    .replace(/<h([1-4])[^>]*>/gi, (m, n) => '\n' + '#'.repeat(Number(n) + 1) + ' ')
    .replace(/<\/(h[1-4]|p|li|dt|dd|tr|div|section|article|dl|ul|ol|table|summary)>/gi, '\n')
    .replace(/<li[^>]*>/gi, '- ').replace(/<dt[^>]*>/gi, '- ').replace(/<dd[^>]*>/gi, ': ')
    .replace(/<t[dh][^>]*>/gi, ' | ').replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, ' ');
  const text = decode(html).split('\n').map((l) => l.replace(/\s+/g, ' ').trim()).filter(Boolean).join('\n');
  return `<page url="https://sereinora.com${path}" title="${title.replace(/"/g, "'")}">\n${text}\n</page>`;
}

const knowledge = PAGES.map(pageText).join('\n\n');

// Search index for the built-in (no-AI) answers in the browser: one entry per page section.
const index = [];
for (const block of knowledge.split('\n\n')) {
  const m = block.match(/^<page url="https:\/\/sereinora\.com([^"]*)" title="([^"]*)">\n([\s\S]*)\n<\/page>$/);
  if (!m) continue;
  const [, path, title, body] = m;
  let heading = title.split(/[|:]/)[0].trim();
  let buf = [];
  const flush = () => {
    const text = buf.join(' ').replace(/\s+/g, ' ').trim();
    if (text.length > 40) index.push({ u: path, h: heading, t: text.slice(0, 1200) });
    buf = [];
  };
  const SKIP = /^(Sources|On this page|Answer for one venue|Why it matters)$/i;
  for (const line of body.split('\n')) {
    const h = line.match(/^#{2,5} (.+)$/);
    if (h) { flush(); heading = h[1].trim(); continue; }
    if (SKIP.test(heading) || /^Home \(https:\/\/sereinora\.com\/\) \//.test(line)) continue;
    // Plain-language text only: drop link URLs (the page link is added at answer time) and table pipes.
    buf.push(line.replace(/\s*\((https?:\/\/|mailto:)[^)]*\)/g, '').replace(/\s*\|\s*/g, ', ').replace(/^,\s*/, ''));
  }
  flush();
}
writeFileSync(join(root, 'assets/assistant-index.json'), JSON.stringify(index));
console.log(`search index: ${index.length} sections`);
writeFileSync(join(root, 'assistant/worker/src/knowledge.js'),
  '// Generated by assistant/build-knowledge.mjs from the published pages. Do not edit by hand.\n' +
  `export const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`);
console.log(`knowledge: ${PAGES.length} pages, ${knowledge.length} characters (~${Math.round(knowledge.length / 4)} tokens)`);
